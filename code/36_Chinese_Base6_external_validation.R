# ============================================================
# 11. Calibration slope
#
# Use frozen external LP
#
# Ideal slope = 1
# ============================================================

external_data$lp_centered <-
  external_data$lp_base6 -
  LP_center


cal_slope_fit <- coxph(

  Surv(
    time_day,
    status
  ) ~
    lp_centered,

  data =
    external_data,

  ties =
    "efron"
)


calibration_slope <-
  as.numeric(
    coef(
      cal_slope_fit
    )[1]
  )


calibration_slope_se <-
  sqrt(
    vcov(
      cal_slope_fit
    )[1, 1]
  )


calibration_slope_ci <- c(

  lower =
    calibration_slope -
    1.96 *
    calibration_slope_se,

  upper =
    calibration_slope +
    1.96 *
    calibration_slope_se
)


cat("\n============================================\n")
cat("F. External calibration slope\n")
cat("============================================\n")

