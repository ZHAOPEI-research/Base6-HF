# ============================================================
# 13. Calibration groups
#
# External n=346, deaths~47
#
# Deciles may be too sparse.
# Use quintiles first.
# ============================================================

cuts <-
  unique(
    quantile(
      external_data$risk_1y,
      probs =
        seq(
          0,
          1,
          0.2
        ),
      na.rm =
        TRUE
    )
  )


external_data$cal_group <-
  cut(

    external_data$risk_1y,

    breaks =
      cuts,

    include.lowest =
      TRUE,

    labels =
      FALSE
  )


calibration_groups <- list()


for (g in sort(
  unique(
    external_data$cal_group
  )
)) {

  dg <-
    external_data[
      external_data$cal_group ==
        g,
    ]


  sf_g <-
    survfit(

      Surv(
        time_day,
        status
      ) ~ 1,

      data =
        dg
    )


  s365_g <-
    summary(

      sf_g,

      times =
        365,

      extend =
        TRUE

    )$surv


  calibration_groups[[
    length(
      calibration_groups
    ) +
      1
  ]] <-
    data.frame(

      group =
        g,

      n =
        nrow(
          dg
        ),

      deaths =
        sum(
          dg$status == 1
        ),

      mean_predicted =
        mean(
          dg$risk_1y
        ),

      observed_KM =
        1 -
        as.numeric(
          s365_g
        )
    )
}


calibration_groups <-
  bind_rows(
    calibration_groups
  )


