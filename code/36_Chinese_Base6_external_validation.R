# ============================================================
# 9. IPCW Brier score
# ============================================================

ipcw_brier <- function(
    time,
    status,
    pred_risk,
    t
) {

  censor_status <-
    1 -
    status

  km_cens <-
    survfit(
      Surv(
        time,
        censor_status
      ) ~ 1
    )

  G_at <- function(s) {

    as.numeric(
      summary(
        km_cens,
        times = s,
        extend = TRUE
      )$surv
    )
  }


  G_t <-
    G_at(t)


  contribution <-
    numeric(
      length(time)
    )


  for (i in seq_along(time)) {

    if (
      status[i] == 1 &&
      time[i] <= t
    ) {

      G_i <-
        G_at(
          max(
            time[i] -
              1e-8,
            0
          )
        )

      if (
        is.finite(G_i) &&
        G_i > 0
      ) {

        contribution[i] <-
          (1 -
             pred_risk[i])^2 /
          G_i
      }

    } else if (
      time[i] > t
    ) {

      if (
        is.finite(G_t) &&
        G_t > 0
      ) {

        contribution[i] <-
          pred_risk[i]^2 /
          G_t
      }
    }
  }


  mean(
    contribution
  )
}


brier_1y <-
  ipcw_brier(

    time =
      external_data$time_day,

    status =
      external_data$status,

    pred_risk =
      external_data$risk_1y,

    t =
      365
  )


